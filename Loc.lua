-- Sorted fragment lists for prefix/suffix composition ("Shopping for " .. name).
local prefixes, suffixes = {}, {}
for en in pairs(L) do
    if en:sub(-1) == " " then prefixes[#prefixes+1] = en end
    if en:sub(1, 1) == " " then suffixes[#suffixes+1] = en end
end
table.sort(prefixes, function(a, b) return #a > #b end)
table.sort(suffixes, function(a, b) return #a > #b end)

local function lookup(s, depth)
    if depth > 4 or type(s) ~= "string" or s == "" then return nil end
    local hit = L[s]
    if hit then return hit end
    for i = 1, #prefixes do
        local p = prefixes[i]
        if #s > #p and s:sub(1, #p) == p then
            local rest = s:sub(#p + 1)
            local r = lookup(rest, depth + 1) or rest
            return L[p] .. r
        end
    end
    for i = 1, #suffixes do
        local p = suffixes[i]
        if #s > #p and s:sub(-#p) == p then
            local rest = s:sub(1, #s - #p)
            local r = lookup(rest, depth + 1) or rest
            return r .. L[p]
        end
    end
    return nil
end

--- Translates a UI string to Russian when a dictionary entry exists.
--- Unknown strings (names, links, numbers, server tokens) pass through unchanged.
---@param s string?  Source text.
---@return string?   Translated text, or the input unchanged.
function NS.CB_L(s)
    if type(s) ~= "string" or s == "" then return s end
    return lookup(s, 0) or s
end
